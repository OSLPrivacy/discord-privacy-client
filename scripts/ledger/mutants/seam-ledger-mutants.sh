#!/usr/bin/env bash
# THE SEAM LEDGER, PROVEN TO FAIL. Ledger 9.
#
# Ledger 9 lives in apps/osl-hub/src/seam_ledger.rs because its inputs are the
# Rust receipt machinery. These mutants drive the two halves it can be attacked
# through:
#
#   A  the BASELINE gains an id that no live row matches   -> FAIL, "baseline is stale"
#   B  one baseline id is SWAPPED for another, count fixed -> FAIL, "DRIFTED"
#   C  the baseline is corrupted                           -> FAIL, "IS NOT USABLE"
#   D  a RECEIPT FILE is deleted                           -> FAIL, the row changes id
#
# The fifth -- publishing a provider with no receipt -- is a source edit to
# NATIVE_APPS and needs a recompile; it is run separately and its output is in
# scripts/ledger/transcripts/ledger-9-seam.txt.
#
# Every mutation is verified to have applied, and every cargo exit code is read
# directly rather than through a pipeline. This project has shipped a ledger
# that printed FAIL and exited 0.
#
#   bash scripts/ledger/mutants/seam-ledger-mutants.sh

set -uo pipefail
cd "$(dirname "$0")/../../.."
ROOT=$(pwd)
BASELINE=apps/osl-hub/carry-receipts/seam-ledger-baseline.json
RECEIPT=apps/osl-hub/carry-receipts/telegram.json
SOURCE=apps/osl-hub/src/native_apps.rs
TEST='seam_ledger::tests::the_seam_ledger_is_at_its_recorded_baseline'
FAILURES=0
export CARGO_TARGET_DIR="${CARGO_TARGET_DIR:-$ROOT/.cargo-target}"

# Snapshot the files these mutants edit, and restore from the SNAPSHOT.
#
# The first version of this script restored with `git checkout --`, which
# silently does nothing for a file git does not track yet. The baseline was
# untracked, so mutant C left it corrupted and mutants D and E then ran against
# a broken baseline and "failed" for the wrong reason -- they reported the
# baseline unusable rather than the thing being mutated. A restore that can
# silently do nothing is the same class of defect as a gate that can silently
# pass, so this one is verified with `cmp`.
SNAPSHOT=$(mktemp -d /tmp/osl-seam-snapshot.XXXXXX)
cp "$ROOT/$BASELINE" "$SNAPSHOT/baseline.json"
cp "$ROOT/$RECEIPT" "$SNAPSHOT/receipt.json"
cp "$ROOT/$SOURCE" "$SNAPSHOT/native_apps.rs"

restore() {
  cp "$SNAPSHOT/baseline.json" "$ROOT/$BASELINE"
  cp "$SNAPSHOT/receipt.json" "$ROOT/$RECEIPT"
  cp "$SNAPSHOT/native_apps.rs" "$ROOT/$SOURCE"
  cmp -s "$SNAPSHOT/baseline.json" "$ROOT/$BASELINE" || { echo "  *** RESTORE FAILED: $BASELINE ***"; exit 9; }
  cmp -s "$SNAPSHOT/receipt.json" "$ROOT/$RECEIPT" || { echo "  *** RESTORE FAILED: $RECEIPT ***"; exit 9; }
  cmp -s "$SNAPSHOT/native_apps.rs" "$ROOT/$SOURCE" || { echo "  *** RESTORE FAILED: $SOURCE ***"; exit 9; }
}
trap 'restore; rm -rf "$SNAPSHOT"' EXIT

run_ledger() { # prints the report, returns cargo's REAL exit code
  local log
  log=$(mktemp)
  flock -o /tmp/osl-cargo.lock cargo test --manifest-path apps/osl-hub/Cargo.toml \
    --features core --lib -j 4 -- --exact --nocapture "$TEST" > "$log" 2>&1
  local code=$?
  sed -n '/LEDGER 9/,$p' "$log" | head -60
  rm -f "$log"
  return $code
}

expect_exit() {
  if [ "$1" -eq "$2" ]; then
    echo "  OK: $3 exited $1 as required"
  else
    echo "  *** GATE FAILURE: $3 exited $1, wanted $2 ***"
    FAILURES=$((FAILURES + 1))
  fi
}

echo "STARVATION TRANSCRIPT -- LEDGER 9, THE SEAM LEDGER"
echo "generated by scripts/ledger/mutants/seam-ledger-mutants.sh at $(date -u +%Y-%m-%dT%H:%M:%SZ)"
echo "head: $(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null || echo unknown)"
echo
echo "=== CONTROL: the unmutated tree ==="
run_ledger
expect_exit "$?" 0 "control"

echo
echo "=== MUTANT A: the baseline lists a violation that no longer exists ==="
python3 - "$ROOT/$BASELINE" <<'PY'
import json, sys
p = sys.argv[1]
d = json.load(open(p))
d["ids"].append("signal:published-without-a-sound-receipt")
d["defects"]["signal:published-without-a-sound-receipt"] = "D-000"
d["openViolations"] = len(d["ids"])
json.dump(d, open(p, "w"), indent=2)
print("added a phantom id, openViolations ->", d["openViolations"])
PY
run_ledger
expect_exit "$?" 101 "mutant A (baseline stale)"
restore

echo
echo "=== MUTANT B: one baseline id SWAPPED for another -- THE COUNT DOES NOT MOVE ==="
python3 - "$ROOT/$BASELINE" <<'PY'
import json, sys
p = sys.argv[1]
d = json.load(open(p))
if not d["ids"]:
    sys.exit("MUTATION DID NOT APPLY: the baseline has no ids to swap")
gone = d["ids"][0]
d["ids"][0] = "signal:published-without-a-sound-receipt"
d["defects"].pop(gone, None)
d["defects"]["signal:published-without-a-sound-receipt"] = "D-000"
json.dump(d, open(p, "w"), indent=2)
print("swapped", gone, "-> signal:published-without-a-sound-receipt; count unchanged at", len(d["ids"]))
PY
run_ledger
expect_exit "$?" 101 "mutant B (swap at an unchanged count)"
restore

echo
echo "=== MUTANT C: the baseline is corrupted ==="
printf '{ "schema": "osl-seam-ledger-baseline-v1", "openViolations": 99, "ids": [] }\n' > "$ROOT/$BASELINE"
run_ledger
expect_exit "$?" 101 "mutant C (unusable baseline)"
restore

echo
echo "=== MUTANT D: a live carry receipt is DELETED from the tree ==="
if [ ! -f "$ROOT/$RECEIPT" ]; then
  echo "  *** MUTATION DID NOT APPLY: $RECEIPT is not there to delete ***"
  exit 9
fi
rm "$ROOT/$RECEIPT"
run_ledger
expect_exit "$?" 101 "mutant D (receipt deleted)"
restore

echo
echo "=== MUTANT E: a provider is PUBLISHED with no live carry receipt ==="
echo "    The mutant this ledger exists for. It edits NATIVE_APPS and recompiles the"
echo "    crate; the ledger's own code is untouched, so it cannot be satisfied by"
echo "    editing the gate, and absorbing it into the baseline would be a visible +1"
echo "    that must also name a defect in \"defects\" or the baseline is unusable."
python3 - "$ROOT/$SOURCE" <<'PYE'
import sys
path = sys.argv[1]
s = open(path).read()
anchor = (
    '        id: NativeAppId::Signal,\n'
    '        display_name: "Signal",\n'
    '        adapter_service: AdapterService::Signal,\n'
    '        adapter_surface: AdapterSurface::InstalledNativeClient,\n'
    '        adapter_support: SupportLevel::ComingSoon,'
)
if anchor not in s:
    sys.exit("MUTATION DID NOT APPLY: the Signal manifest is not shaped as expected")
open(path, "w").write(
    s.replace(anchor, anchor.replace("SupportLevel::ComingSoon", "SupportLevel::Experimental"), 1)
)
print("Signal: adapter_support ComingSoon -> Experimental, with no receipt in carry-receipts/")
PYE
if [ $? -ne 0 ]; then echo "  *** MUTATION DID NOT APPLY ***"; exit 9; fi
run_ledger
expect_exit "$?" 101 "mutant E (a provider published on nothing)"
restore

echo
if [ "$FAILURES" -eq 0 ]; then
  echo "ALL MUTANTS REJECTED. The seam ledger can fail."
  exit 0
fi
echo "$FAILURES MUTANT(S) WERE NOT REJECTED. The ledger is decoration until this is 0."
exit 1
