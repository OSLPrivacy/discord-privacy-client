#!/usr/bin/env bash
# THE PIN CENSUS, PROVEN TO FAIL. Ledger 10.
#
# Three mutants, each a real edit to a real source file in a real copy of the
# tree, read by the same code path CI runs (`--root=`). The baseline read is
# always the real scripts/ledger/pin-baseline.json, so none of these can be
# satisfied by editing the gate.
#
#   A  a new source-text pin is written           -> must FAIL, naming file:line
#   B  a pin is removed, baseline not lowered     -> must FAIL, "baseline is stale"
#   C  one removed AND one added, count unchanged -> must FAIL on the ids
#
# EVERY MUTATION IS VERIFIED TO HAVE APPLIED. A mutant that silently does not
# mutate reports GREEN and proves nothing; that happened on the first run of
# this script and is the reason `require_applied` exists.
#
#   bash scripts/ledger/mutants/pins-mutants.sh
#
# Exit 0 only when the control is GREEN and all three mutants are RED.

set -uo pipefail
cd "$(dirname "$0")/../../.."
ROOT=$(pwd)
ELIDE='^ *(apps|services|crates|scripts|docs|03-|keyserver|infra|src-tauri|tools|cipher|vmqa|webview|plan/|selector)'
TARGET=apps/osl-hub-ui/src/onboarding-presets.test.ts
FAILURES=0

copy_tree() {
  local tmp
  tmp=$(mktemp -d /tmp/osl-pins-mutant.XXXXXX)
  rsync -a --exclude node_modules --exclude .git --exclude target --exclude dist "$ROOT/" "$tmp/" >/dev/null
  echo "$tmp"
}

# Run the census against a tree and report the REAL exit code, never a pipeline's.
run_census() {
  local tmp=$1
  node "$ROOT/scripts/ledger/pins.mjs" --root="$tmp" 2>&1 | grep -Ev "$ELIDE"
  return "${PIPESTATUS[0]}"
}

expect_exit() { # $1 = actual, $2 = wanted, $3 = label
  if [ "$1" -eq "$2" ]; then
    echo "  OK: $3 exited $1 as required"
  else
    echo "  *** GATE FAILURE: $3 exited $1, wanted $2 ***"
    FAILURES=$((FAILURES + 1))
  fi
}

delete_one_pin() { # $1 = tree; prints the deleted line
  python3 - "$1/$TARGET" <<'PY'
import sys
path = sys.argv[1]
lines = open(path).read().split("\n")
out, killed = [], None
for line in lines:
    if killed is None and "expect(presetContent).toContain(" in line:
        killed = line.strip()
        continue
    out.append(line)
if not killed:
    sys.exit("MUTATION DID NOT APPLY: no expect(presetContent).toContain( in " + path)
open(path, "w").write("\n".join(out))
print(killed)
PY
}

add_one_pin() { # $1 = tree, $2 = binding name
  python3 - "$1/$TARGET" "$2" <<'PY'
import sys
path, name = sys.argv[1], sys.argv[2]
s = open(path).read()
marker = 'const source = readFileSync(new URL("./main.ts", import.meta.url), "utf8");'
if marker not in s:
    sys.exit("MUTATION DID NOT APPLY: anchor missing in " + path)
s = s.replace(marker, marker + f'\nconst {name} = readFileSync(new URL("./main.ts", import.meta.url), "utf8");', 1)
s += f'\nit("MUTANT: a source-text pin", () => {{\n  expect({name}).toContain("protectionPreset");\n}});\n'
open(path, "w").write(s)
print(f'expect({name}).toContain("protectionPreset")   [{name} = readFileSync(./main.ts)]')
PY
}

echo "STARVATION TRANSCRIPT -- LEDGER 10, THE PIN CENSUS"
echo "generated by scripts/ledger/mutants/pins-mutants.sh at $(date -u +%Y-%m-%dT%H:%M:%SZ)"
echo "head: $(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null || echo unknown)"
echo
echo "=== CONTROL: the unmutated tree ==="
echo "\$ node scripts/ledger/pins.mjs"
node "$ROOT/scripts/ledger/pins.mjs"
expect_exit "$?" 0 "control"

echo
echo "=== MUTANT A: a new source-text pin is written (the D-221 shape) ==="
tmp=$(copy_tree)
added=$(add_one_pin "$tmp" mutantPin) || { echo "  *** MUTATION DID NOT APPLY ***"; exit 9; }
echo "\$ # added to $TARGET:  $added"
echo "\$ node scripts/ledger/pins.mjs --root=\$tmp"
run_census "$tmp"
expect_exit "$?" 1 "mutant A (pin added)"
rm -rf "$tmp"

echo
echo "=== MUTANT B: a pin is REMOVED and the baseline is not lowered ==="
tmp=$(copy_tree)
removed=$(delete_one_pin "$tmp") || { echo "  *** MUTATION DID NOT APPLY ***"; exit 9; }
echo "\$ # deleted from $TARGET:  $removed"
echo "\$ node scripts/ledger/pins.mjs --root=\$tmp"
run_census "$tmp"
expect_exit "$?" 1 "mutant B (pin removed, baseline stale)"
rm -rf "$tmp"

echo
echo "=== MUTANT C: one pin removed AND one added -- THE COUNT DOES NOT MOVE ==="
echo "    scripts/ledger/all.mjs:28 -- \"same count, different ids -> FAIL.\""
tmp=$(copy_tree)
removed=$(delete_one_pin "$tmp") || { echo "  *** MUTATION DID NOT APPLY ***"; exit 9; }
added=$(add_one_pin "$tmp" swappedIn) || { echo "  *** MUTATION DID NOT APPLY ***"; exit 9; }
echo "\$ # deleted:  $removed"
echo "\$ # added:    $added"
echo "\$ node scripts/ledger/pins.mjs --root=\$tmp"
run_census "$tmp"
expect_exit "$?" 1 "mutant C (swap at an unchanged count)"
rm -rf "$tmp"

echo
if [ "$FAILURES" -eq 0 ]; then
  echo "ALL MUTANTS REJECTED. The pin census can fail, in all three directions."
  exit 0
fi
echo "$FAILURES MUTANT(S) WERE NOT REJECTED. The census is decoration until this is 0."
exit 1
